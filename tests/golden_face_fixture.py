# Original capture: 512x600 image, bbox (172, 132, 184, 201), ied 84.0196...
_SRC_BBOX = (172, 132, 184, 201)
_SRC_IED = 84.0196182544822
_SRC_W, _SRC_H = 512, 600


def _compute_face_roi_padding(face_w: int, face_h: int):
    """Mirror RetouchEngine._compute_face_roi_padding (engine.py) — regions
    supplied via ctx.face_contexts must already be sized to this same ROI
    crop, since _stage_per_face/​_process_one_face reuse cached regions
    as-is instead of re-parsing (see engine.py's "Region parsing — or
    reuse cached regions from ctx.face_contexts")."""
    return (
        int(face_h * 0.8), int(face_h * 1.8),
        int(face_w * 0.6), int(face_w * 0.6),
    )


def make_face_context(img_w: int, img_h: int, img_bgr: np.ndarray, index: int = 0):
    """Build a real FaceContext (FaceData + FaceRegions) for a synthetic image.

    Landmarks are the frozen normalized coordinates above (real anatomical
    topology). ``face_data.bbox``/``landmarks`` are full-image-relative (as
    real detection output would be); ``regions`` masks are built at
    ROI-crop size with ROI-relative landmarks, matching the convention
    RetouchEngine._stage_per_face uses when reusing cached face_contexts
    (it does not re-crop/re-shift pre-supplied regions). No BiSeNet/ONNX
    involved, so this is deterministic and CPU-only.
    """
    from retouch.detection import _Landmark, _LandmarkCompat, FaceData, FaceContext
    from retouch.parsing import FaceParser

    lm_list = [_Landmark(x, y, z) for (x, y, z) in _RAW_LANDMARKS]
    compat = _LandmarkCompat(lm_list)

    # Scale bbox/ied from the source capture proportionally to the target image.
    scale_x = img_w / _SRC_W
    scale_y = img_h / _SRC_H
    bx, by, bw, bh = _SRC_BBOX
    face_x, face_y = int(bx * scale_x), int(by * scale_y)
    face_w, face_h = int(bw * scale_x), int(bh * scale_y)
    ied = _SRC_IED * ((scale_x + scale_y) / 2.0)

    face_data = FaceData(
        landmarks=compat,
        bbox=(face_x, face_y, face_w, face_h),
        ied=ied,
        confidence=0.99,
        confidence_source="retinaface",  # measured — see safe_auto.MEASURED_CONFIDENCE_SOURCES
    )

    # ROI crop, matching engine.py::_stage_per_face exactly.
    pad_t, pad_b, pad_l, pad_r = _compute_face_roi_padding(face_w, face_h)
    roi_y1 = max(0, face_y - pad_t)
    roi_y2 = min(img_h, face_y + face_h + pad_b)
    roi_x1 = max(0, face_x - pad_l)
    roi_x2 = min(img_w, face_x + face_w + pad_r)
    roi_h, roi_w = roi_y2 - roi_y1, roi_x2 - roi_x1
    canvas = img_bgr[roi_y1:roi_y2, roi_x1:roi_x2]

    shifted_lm = [
        _Landmark((x * img_w - roi_x1) / roi_w, (y * img_h - roi_y1) / roi_h, z)
        for (x, y, z) in _RAW_LANDMARKS
    ]
    shifted_compat = _LandmarkCompat(shifted_lm)

    parser = FaceParser()
    parser._sess = None  # force landmark-only path — no ONNX, deterministic, OS-independent
    regions = parser._landmark_fallback_only(shifted_compat, canvas, person_mask=None, ied=ied)

    # light_direction stays None (fixture builds no lighting estimate), so
    # the populated-key-light branch in perf_optimizations._process_face_core's
    # sculpt/relight coherence check is not exercised by this fixture.
    return FaceContext(face_data=face_data, regions=regions, index=index)


def make_synthetic_face_image(w: int = 320, h: int = 384) -> np.ndarray:
    """Deterministic synthetic image with a plausible skin-toned face region.

    Not a real photo — a fixed gradient + noise field seeded for
    reproducibility, with a mid-tone elliptical region roughly where the
    frozen landmarks place a face, so skin ops see believable input color.
    """
    rng = np.random.default_rng(seed=7)
    yy = np.linspace(0, 255, h, dtype=np.float32)[:, None]
    xx = np.linspace(0, 255, w, dtype=np.float32)[None, :]
    base = (yy + xx) * 0.25
    noise = rng.normal(0, 6, (h, w, 3)).astype(np.float32)
    img = np.stack([base * 0.6 + 40, base * 0.5 + 90, base * 0.7 + 110], axis=-1) + noise

    cx, cy = int(0.47 * w), int(0.41 * h)
    ax, ay = int(0.20 * w), int(0.28 * h)
    yv, xv = np.ogrid[:h, :w]
    ellipse = (((xv - cx) / max(ax, 1)) ** 2 + ((yv - cy) / max(ay, 1)) ** 2) <= 1.0
    skin_bgr = np.array([120.0, 150.0, 200.0], dtype=np.float32)
    img[ellipse] = skin_bgr + rng.normal(0, 4, (ellipse.sum(), 3)).astype(np.float32)

    return np.clip(img, 0, 255).astype(np.uint8)
